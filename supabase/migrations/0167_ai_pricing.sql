-- 0167 ai_pricing (ME in docs/AI_ESTIMATING_BUILD_SPEC.md 5.6, WS6)
--
-- The G3 cost library (sources, items, observations), the editable pricing
-- policy row, vendor quote extractions, and the priced versions of an AI
-- Estimating run with their lines. Applied to DEV only during the build
-- (letter order MA..MG = 0163..0169; MC 0165 already adds the ai_pricing
-- job type and the two file_access_events sources). Idempotent: safe to
-- re-run. Every table is server-only: RLS enabled and forced, no policies,
-- anon and authenticated revoked (the service-role backend bypasses RLS).
--
-- Pricing data is internal: these tables hold estimator unit values and
-- vendor amounts and are read only by the pricing router (AI_PRICING_VIEW
-- roles) and the ai_pricing job. Nothing here reaches the estimator role.

create extension if not exists pg_trgm;

-- ---------------------------------------------------------------------------
-- Cost library: one source per ingested estimate workbook, one item per
-- (library key, unit of measure), one observation per workbook line.
-- ---------------------------------------------------------------------------
create table if not exists cost_sources (
  id              uuid primary key default gen_random_uuid(),
  project_id      uuid not null,
  file_id         uuid,
  filename        text,
  workbook_date   date,
  labor_rate      numeric,
  parser_version  int,
  sha256          text,
  line_count      int not null default 0,
  skipped         jsonb,
  created_at      timestamptz not null default now()
);
create unique index if not exists cost_sources_project_file_uq
  on cost_sources (project_id, coalesce(file_id::text, filename));
create index if not exists cost_sources_project_idx on cost_sources (project_id);

create table if not exists cost_items (
  id            uuid primary key default gen_random_uuid(),
  item_key      text not null,
  uom           text not null,
  family        text,
  item_class    text,
  search_text   text not null default '',
  descriptions  jsonb,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  unique (item_key, uom)
);
create index if not exists cost_items_search_trgm_idx
  on cost_items using gin (search_text gin_trgm_ops);
create index if not exists cost_items_family_idx on cost_items (family, uom);

create table if not exists cost_observations (
  id                  bigint generated by default as identity primary key,
  source_id           uuid references cost_sources(id) on delete cascade,
  item_id             uuid references cost_items(id) on delete set null,
  project_id          uuid not null,
  item_key            text not null,
  family              text,
  item_class          text,
  uom                 text not null,
  unit_labor_hours    numeric,
  unit_material_cost  numeric,
  observed_on         date,
  raw_description     text,
  group_name          text,
  source_ref          text,
  excluded            boolean not null default false,
  created_at          timestamptz not null default now()
);
create unique index if not exists cost_observations_source_ref_uq
  on cost_observations (source_id, source_ref) where source_id is not null;
create index if not exists cost_observations_item_idx on cost_observations (item_key, uom);
create index if not exists cost_observations_project_idx on cost_observations (project_id);

-- ---------------------------------------------------------------------------
-- The pricing policy (pricing_policy.PricingPolicy.to_dict): one row, edited
-- by VERIFY_ROLES through PUT /ai-estimating/pricing/settings (audited).
-- ---------------------------------------------------------------------------
create table if not exists ai_pricing_settings (
  id          int primary key default 1 check (id = 1),
  policy      jsonb not null default '{}'::jsonb,
  version     int not null default 1,
  updated_by  uuid references profiles(id) on delete set null,
  updated_at  timestamptz not null default now()
);
insert into ai_pricing_settings (id) values (1) on conflict (id) do nothing;

-- ---------------------------------------------------------------------------
-- Vendor quotes uploaded to a run (run-private storage under
-- plans-reader/{run_id}/quotes/) and what the parser read from them.
-- ---------------------------------------------------------------------------
create table if not exists vendor_quote_extractions (
  id              uuid primary key default gen_random_uuid(),
  run_id          uuid not null references plans_reader_runs(id) on delete cascade,
  file_sha256     text not null,
  filename        text,
  storage_path    text,
  size_bytes      int,
  category        text,
  vendor          text,
  quote_number    text,
  amount_pretax   numeric,
  tax_included    boolean,
  parser          text not null default 'text' check (parser in ('text', 'llm', 'manual')),
  parser_version  int,
  status          text not null default 'pending'
                  check (status in ('pending', 'parsed', 'needs_review', 'failed')),
  lines           jsonb,
  notes           jsonb,
  warnings        jsonb,
  error           text,
  selected        boolean not null default false,
  created_by      uuid references profiles(id) on delete set null,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  unique (run_id, file_sha256)
);
create index if not exists vendor_quote_extractions_run_idx on vendor_quote_extractions (run_id);

-- ---------------------------------------------------------------------------
-- Priced versions of a run (one per pricing pass; older versions go stale
-- when a newer BOQ or pricing version lands) and their lines.
-- ---------------------------------------------------------------------------
create table if not exists plans_reader_pricing (
  id                           uuid primary key default gen_random_uuid(),
  run_id                       uuid not null references plans_reader_runs(id) on delete cascade,
  version                      int not null,
  boq_version                  int,
  status                       text not null
                               check (status in ('priced', 'provisional', 'blocked')),
  policy                       jsonb,
  policy_version               text,
  library_fingerprint          text,
  excluded_project_ids_sha256  text,
  inputs_sha256                text,
  context                      jsonb,
  categories                   jsonb,
  verify_draft                 jsonb,
  workbook_basis               jsonb,
  range_low                    numeric,
  range_high                   numeric,
  quality_summary              jsonb,
  unpriced                     jsonb,
  blockers                     jsonb,
  warnings                     jsonb,
  storage_path                 text,
  filename                     text,
  stale                        boolean not null default false,
  instruction                  text,
  created_by                   uuid references profiles(id) on delete set null,
  created_at                   timestamptz not null default now(),
  unique (run_id, version)
);
create index if not exists plans_reader_pricing_run_idx on plans_reader_pricing (run_id, version desc);

create table if not exists plans_reader_priced_lines (
  pricing_id  uuid not null references plans_reader_pricing(id) on delete cascade,
  line_id     text not null,
  line        jsonb not null,
  primary key (pricing_id, line_id)
);

